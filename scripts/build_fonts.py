"""Cut the bundled Noto Sans SC into small WOFF2 pieces, each with the unicode-range it covers.

    .venv/Scripts/python scripts/build_fonts.py        (needs fonttools + brotli: requirements-dev.txt)

The page then only fetches and decodes the pieces whose characters are on screen, the way Google Fonts serves
Chinese. The whole 17 MB variable font took 0.4 s (cached) to 1.9 s (first load) of every window start before
the page drew (2026-11-11). The source font stays at web/fonts/NotoSansSC-VF.ttf; this writes
web/fonts/noto-sc/*.woff2 and web/fonts/noto-sc.css. Rerun it only when the source font changes.
"""
from __future__ import annotations

import hashlib
import shutil
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "web" / "fonts" / "NotoSansSC-VF.ttf"
OUT = ROOT / "web" / "fonts" / "noto-sc"
CSS = ROOT / "web" / "fonts" / "noto-sc.css"


def gb2312_level(ch: str) -> int:
    """1: the 3755 most used characters, 2: the next 3008, 0: neither (GB 2312's own two levels)."""
    try:
        b = ch.encode("gb2312")
    except UnicodeEncodeError:
        return 0
    if len(b) != 2:
        return 0
    return 1 if 0xB0 <= b[0] <= 0xD7 else 2 if 0xD8 <= b[0] <= 0xF7 else 0


def is_han(cp: int) -> bool:
    return 0x3400 <= cp <= 0x9FFF or 0xF900 <= cp <= 0xFAFF or 0x20000 <= cp <= 0x3FFFF


def chunks(seq: list[int], n: int) -> list[list[int]]:
    size = -(-len(seq) // n)
    return [seq[i:i + size] for i in range(0, len(seq), size)]


def ranges(cps: list[int]) -> str:
    cps = sorted(cps)
    out, start, prev = [], cps[0], cps[0]
    for cp in cps[1:] + [None]:
        if cp is not None and cp == prev + 1:
            prev = cp
            continue
        out.append(f"U+{start:X}" if start == prev else f"U+{start:X}-{prev:X}")
        if cp is not None:
            start = prev = cp
    return ", ".join(out)


def main() -> None:
    cmap = TTFont(SRC).getBestCmap()
    cps = sorted(cmap)
    # every character the interface itself writes: one piece the window always needs, so the screen it opens
    # on is drawn from two pieces; what the user writes pulls in the others as it shows
    ui_text = "".join(p.read_text(encoding="utf-8") for p in [*(ROOT / "web" / "i18n").glob("*.json"),
                                                            *(ROOT / "web").glob("*.js"), ROOT / "web" / "index.html"])
    ui = sorted({ord(ch) for ch in ui_text if is_han(ord(ch)) and ord(ch) in cmap})
    taken = set(ui)
    common = [cp for cp in cps if is_han(cp) and cp not in taken and gb2312_level(chr(cp)) == 1]
    second = [cp for cp in cps if is_han(cp) and cp not in taken and gb2312_level(chr(cp)) == 2]
    rare = [cp for cp in cps if is_han(cp) and cp not in taken and not gb2312_level(chr(cp))]
    other = [cp for cp in cps if not is_han(cp)]              # Latin, digits, punctuation, kana, symbols
    pieces = [other, ui] + chunks(common, 6) + chunks(second, 6) + chunks(rare, 14)

    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    faces = []
    for i, piece in enumerate(pieces):
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = ["*"]
        opts.name_IDs = ["*"]
        opts.notdef_outline = True
        font = TTFont(SRC)
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=piece)
        sub.subset(font)
        font.flavor = "woff2"
        tmp = OUT / f"{i:02d}.tmp"
        font.save(tmp)
        # the name carries the content: the server lets the browser keep such a file for good (core/server.py)
        name = f"{i:02d}-{hashlib.sha1(tmp.read_bytes()).hexdigest()[:10]}.woff2"
        tmp.rename(OUT / name)
        faces.append("@font-face {\n  font-family: \"Noto Sans SC\";\n"
                     f"  src: url(\"noto-sc/{name}\") format(\"woff2\");\n"
                     "  font-weight: 100 900;\n  font-display: swap;\n"
                     f"  unicode-range: {ranges(piece)};\n}}\n")
    CSS.write_text("/* generated by scripts/build_fonts.py from NotoSansSC-VF.ttf (SIL OFL, OFL.txt): do not edit */\n"
                   + "".join(faces), encoding="utf-8")
    total = sum(p.stat().st_size for p in OUT.glob("*.woff2"))
    print(f"{len(pieces)} pieces, {total / 1e6:.1f} MB in all, largest "
          f"{max(p.stat().st_size for p in OUT.glob('*.woff2')) / 1e3:.0f} KB")


if __name__ == "__main__":
    main()
