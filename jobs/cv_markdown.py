"""resume.yaml -> the plain-text CV that job tools read.

Job tools (career-ops and most others) take the candidate's CV as one Markdown file. This builds it
from the library (ALL: every entry), in one resume language, in the shape such tools parse:
`## Experience`, then `### Company — Location`, a bold title line, a dates line and bullets.

The fact layer (each entry's notes) goes into a separate "proof points" file only when the user
allows it: tools treat that file as facts they may quote, the same way Resume Studio treats notes.
"""
from __future__ import annotations

from typing import Any

from core.store import to_plain
from resume import model

# Tools find sections by these English headings, whatever language the content is in.
HEADINGS = {"experience": "Experience", "projects": "Projects", "education": "Education",
            "skills": "Skills", "awards": "Awards"}

MARK = "Generated by Resume Studio from {path}. Edit the resume there; changes made here are not kept."


def cv_markdown(doc: Any, lang: str, source: str = "resume.yaml") -> str:
    view = model.build_view(doc, {**to_plain(model.get_version(doc, model.ALL_ID)), "lang": lang})
    p = view["profile"]
    out = [f"<!-- {MARK.format(path=source)} -->", "", f"# {p['name'] or 'CV'}", ""]
    if p["headline"]:
        out += [p["headline"], ""]
    for c in p["contacts"]:
        label = (c["label"] or "").strip()
        value = (c["value"] or c["url"] or "").strip()
        if value:
            out.append(f"**{label.capitalize() or 'Contact'}:** {value}")
    if p["contacts"]:
        out.append("")
    for sec in view["sections"]:
        out += [f"## {HEADINGS.get(sec['id']) or sec['title'] or sec['id']}", ""]
        if sec["kind"] == "list":
            for e in sec["entries"]:
                items = ", ".join(e["tech"]) or "; ".join(e["bullets"])
                out.append(f"- **{e['title']}:** {items}" if e["title"] else f"- {items}")
            out.append("")
            continue
        for e in sec["entries"]:
            head = e["title"] or e["subtitle"] or "—"
            out.append(f"### {head}" + (f" — {e['location']}" if e["location"] else ""))
            out.append("")
            if e["subtitle"] and e["title"]:
                out.append(f"**{e['subtitle']}**")
            if e["dates"]:
                out.append(e["dates"])
            if e["link"]:
                out.append(e["link"])
            if e["tech"]:
                out.append("Tech: " + ", ".join(e["tech"]))
            if any((e["subtitle"] and e["title"], e["dates"], e["link"], e["tech"])):
                out.append("")
            for b in e["bullets"]:
                out.append(f"- {b}")
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def proof_points(doc: Any, lang: str, source: str = "resume.yaml") -> str:
    """Every entry's notes (the fact layer) and evidence folders, titled the way the CV names them.

    The profile's own notes (job-search background, constraints, preferences) are not proof points:
    tools quote proof points in cover letters and messages. They go into the tool's targeting profile
    instead, through the setup chat."""
    out = [f"<!-- {MARK.format(path=source)} -->", "", "# Proof points", "",
           "What really happened behind each CV entry, in the candidate's own notes. Facts only: use them to",
           "back or sharpen claims, never to invent new ones.", ""]
    for e in doc.get("entries") or []:
        notes = str(e.get("notes") or "").strip()
        evidence = [str(x) for x in e.get("evidence") or []]
        if not notes and not evidence:
            continue
        title = model.tr(e.get("title"), lang) or str(e.get("id"))
        sub = model.tr(e.get("subtitle"), lang)
        out += [f"## {title}" + (f" — {sub}" if sub else ""), ""]
        if notes:
            out += [notes, ""]
        if evidence:
            out += ["Evidence: " + ", ".join(evidence), ""]
    return "\n".join(out).rstrip() + "\n"
